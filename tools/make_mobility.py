#!/usr/bin/env python3
"""
Generates MobilityData.kt: the warm-up & mobility catalogue (stretches, dynamic moves, foam rolling,
cardio) from free-exercise-db (github.com/yuhonas/free-exercise-db, The Unlicense).

    python3 tools/make_mobility.py path/to/exercises.json \
        composeApp/src/commonMain/kotlin/com/gym/app/Catalog.kt \
        composeApp/src/commonMain/kotlin/com/gym/app/MobilityData.kt

exercises.json is dist/exercises.json at the commit pinned in Catalog.kt (IMAGE_BASE).
"""
import json
import re
import sys

data_path, catalog_path, out_path = sys.argv[1:4]
data = json.load(open(data_path))
by_id = {e["id"]: e for e in data}

# Strength catalogue names (so cardio machines keep the names you already know) by image id.
main = dict((img, name) for name, img in re.findall(r'ex\("([^"]+)", Equipment\.\w+, "([^"]+)"\)', open(catalog_path).read()))
main_keys = {n.lower() for n in main.values()}

CARDIO = ["Bicycling_Stationary", "Recumbent_Bike", "Elliptical_Trainer", "Rowing_Stationary", "Walking_Treadmill",
          "Jogging_Treadmill", "Running_Treadmill", "Stairmaster", "Step_Mill", "Rope_Jumping"]
CARDIO_NAMES = {"Walking_Treadmill": "Treadmill walk", "Jogging_Treadmill": "Treadmill jog", "Rope_Jumping": "Skipping rope",
                "Recumbent_Bike": "Recumbent bike", "Step_Mill": "Step mill"}
# Bodyweight moves from the strength/plyometrics part of the dataset that make good warm-ups.
EXTRA_DYNAMIC = ["Bodyweight_Squat", "Bodyweight_Walking_Lunge", "Band_Pull_Apart", "Double_Leg_Butt_Kick", "Mountain_Climbers",
                 "Star_Jump", "Fast_Skipping", "Single_Leg_Glute_Bridge", "Butt_Lift_Bridge", "Dead_Bug", "Plank"]
EXTRA_NAMES = {"Double_Leg_Butt_Kick": "Butt kicks", "Star_Jump": "Star jumps", "Fast_Skipping": "Skipping (high knees)",
               "Butt_Lift_Bridge": "Glute bridge", "Bodyweight_Walking_Lunge": "Walking lunge"}
DYNAMIC_WORDS = ["circles", "leg raises", "inchworm", "groiners", "frog hops", "crossover reverse lunge", "world's greatest",
                 "windmills", "torso rotation", "dynamic", "elbows back", "iron crosses", "scissor kick", "toe touchers",
                 "split squats", "sit squats", "pelvic tilt", "superman", "cat stretch", "round the world"]
MUSCLE = {"hamstrings": "Legs", "quadriceps": "Legs", "calves": "Legs", "adductors": "Legs", "abductors": "Legs",
          "glutes": "Glutes", "lower back": "Back", "middle back": "Back", "lats": "Back", "traps": "Back", "neck": "Back",
          "shoulders": "Shoulders", "chest": "Chest", "abdominals": "Core", "biceps": "Biceps", "triceps": "Triceps",
          "forearms": "Other"}
KEEP_CAPS = {"IT"}


def sentence(name):
    """'All Fours Quad Stretch' -> 'All fours quad stretch' (the app's style)."""
    words = name.replace("(prone)", "(lying)").lower().split()
    out = [w.upper() if w.upper() in KEEP_CAPS else w for w in words]
    text = " ".join(out)
    return text[0].upper() + text[1:]


def display_name(e):
    i, name = e["id"], e["name"]
    if i in main:
        return main[i]
    if i in CARDIO_NAMES:
        return CARDIO_NAMES[i]
    if i in EXTRA_NAMES:
        return EXTRA_NAMES[i]
    if name.endswith("-SMR"):
        return "Foam roll: " + name[:-4].lower()
    if e.get("equipment") == "foam roll":
        return "Foam roll: " + name.lower()
    return sentence(name)


def kind(e):
    if e["category"] == "cardio":
        return "Cardio"
    if e["id"] in EXTRA_DYNAMIC:
        return "Dynamic"
    if e["name"].endswith("-SMR") or e.get("equipment") == "foam roll":
        return "FoamRoller"
    n = e["name"].lower()
    return "Dynamic" if any(w in n for w in DYNAMIC_WORDS) else "Stretch"


def equipment(e):
    if e["category"] == "cardio":
        return "Other" if e["id"] == "Rope_Jumping" else "Machine"
    return {"body only": "Bodyweight", None: "Bodyweight"}.get(e.get("equipment"), "Other")


def muscle(e):
    if e["category"] == "cardio":
        return "FullBody"
    return MUSCLE.get((e.get("primaryMuscles") or ["other"])[0], "Other")


chosen = [by_id[i] for i in CARDIO] + [by_id[i] for i in EXTRA_DYNAMIC] + [e for e in data if e["category"] == "stretching"]
entries, seen = [], set()
for e in chosen:
    name = display_name(e)
    key = name.lower()
    if key in seen:
        continue
    seen.add(key)
    entries.append((name, kind(e), muscle(e), equipment(e), e["id"], e))


def kt(s):
    s = " ".join(s.split())
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


order = {"Cardio": 0, "Dynamic": 1, "Stretch": 2, "FoamRoller": 3}
entries.sort(key=lambda t: (order[t[1]], t[0].lower()))
lines = [
    "package com.gym.app",
    "",
    "// GENERATED by tools/make_mobility.py from free-exercise-db (github.com/yuhonas/free-exercise-db,",
    "// The Unlicense). Regenerate rather than hand-editing.",
    "internal object MobilityData {",
    "    val exercises: List<CatalogExercise> = listOf(",
]
for name, k, m, eq, img, _ in entries:
    lines.append(f"        CatalogExercise({kt(name)}, Muscle.{m}, Equipment.{eq}, {kt(img)}, kind = WarmUpKind.{k}),")
lines += ["    )", "", "    /** How-to steps for the image ids above that the strength catalogue doesn't have. */",
          "    val instructions: Map<String, List<String>> = mapOf("]
for name, k, m, eq, img, e in entries:
    if img in main:
        continue
    steps = ", ".join(kt(s) for s in e.get("instructions", []) if s.strip())
    lines.append(f"        {kt(img)} to listOf({steps}),")
lines += ["    )", "}", ""]
open(out_path, "w").write("\n".join(lines))
from collections import Counter
print(len(entries), "entries", dict(Counter(t[1] for t in entries)),
      "| overlapping strength names:", sorted(t[0] for t in entries if t[0].lower() in main_keys))
